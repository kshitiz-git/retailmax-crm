/* --------------------------------- Helpers -------------------------------- */

export type SegmentSource = "computed" | "dataset";

export const segmentOf = (c: Customer, source: SegmentSource): Segment =>
  source === "computed" ? c.computedSegment : c.rfm_segment;

/** C00042 -> 42. NaN when the id has no digits. */
export const customerNumber = (id: string) => parseInt(id.replace(/\D/g, ""), 10);

/** Original HCL rows are C00001-C00500; anything above is generated by the pipeline. */
export const isOriginalRow = (id: string) => {
  const n = customerNumber(id);
  return Number.isNaN(n) || n <= 500;
};

export const mean = (xs: number[]) => (xs.length ? xs.reduce((s, x) => s + x, 0) / xs.length : 0);

export const median = (xs: number[]) => {
  if (!xs.length) return 0;
  const s = [...xs].sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid]! : (s[mid - 1]! + s[mid]!) / 2;
};

export interface SegmentStats {
  segment: Segment;
  count: number;
  /** 0-1 share of all customers. */
  share: number;
  avgRecency: number;
  avgOrders: number;
  avgAov: number;
  revenue: number;
  /** Actual churn_flag rate, 0-1. */
  churnRate: number;
  /** Mean model probability, 0-1. */
  avgChurnProb: number;
}

export function segmentStats(customers: Customer[], source: SegmentSource): Record<Segment, SegmentStats> {
  const total = customers.length;
  const acc = Object.fromEntries(
    SEGMENTS.map((s) => [s, { n: 0, rec: 0, ord: 0, aov: 0, rev: 0, churn: 0, prob: 0 }]),
  ) as Record<Segment, { n: number; rec: number; ord: number; aov: number; rev: number; churn: number; prob: number }>;
  for (const c of customers) {
    const a = acc[segmentOf(c, source)];
    a.n++;
    a.rec += c.last_purchase_days;
    a.ord += c.purchase_freq;
    a.aov += c.avg_order_value;
    a.rev += c.monetary;
    a.churn += c.churn_flag;
    a.prob += c.churnProb;
  }
  return Object.fromEntries(
    SEGMENTS.map((s) => {
      const a = acc[s];
      const n = a.n || 1;
      return [
        s,
        {
          segment: s,
          count: a.n,
          share: total ? a.n / total : 0,
          avgRecency: a.rec / n,
          avgOrders: a.ord / n,
          avgAov: a.aov / n,
          revenue: a.rev,
          churnRate: a.n ? a.churn / a.n : 0,
          avgChurnProb: a.n ? a.prob / a.n : 0,
        } satisfies SegmentStats,
      ];
    }),
  ) as Record<Segment, SegmentStats>;
}

/* ------------------------------ Model wording ----------------------------- */

const FEATURE_NAME: Record<string, string> = {
  purchase_freq: "Purchase frequency",
  avg_order_value: "Average order value",
  last_purchase_days: "Days since last purchase",
  loyalty_points: "Loyalty points",
  age_group: "Age group",
  region: "Region",
};

/** purchase_freq -> "Purchase frequency"; region=East -> "Region: East". */
export function featureLabel(feature: string): string {
  if (FEATURE_NAME[feature]) return FEATURE_NAME[feature]!;
  const eq = feature.indexOf("=");
  if (eq > 0) {
    const col = feature.slice(0, eq);
    return `${FEATURE_NAME[col] ?? col.replace(/_/g, " ")}: ${feature.slice(eq + 1)}`;
  }
  const s = feature.replace(/_/g, " ");
  return s.charAt(0).toUpperCase() + s.slice(1);
}

const NUMERIC_PHRASE: Record<string, { high: string; low: string; fmt: (v: number) => string }> = {
  purchase_freq: { high: "High purchase frequency", low: "Low purchase frequency", fmt: (v) => `${formatNumber(v)} orders` },
  avg_order_value: { high: "High order value", low: "Low order value", fmt: formatCurrency },
  last_purchase_days: { high: "Long gap since last purchase", low: "Very recent purchase", fmt: (v) => `${formatNumber(v)} days` },
  loyalty_points: { high: "High loyalty balance", low: "Few loyalty points", fmt: (v) => `${formatNumber(v)} pts` },
};

/** Largest positive log-odds contribution as a plain sentence, e.g. "Long gap since last purchase (310 days)". */
export function reasonFrom(row: CustomerRow, contributions: Contribution[]): string {
  let best: Contribution | undefined;
  for (const c of contributions) if (c.value > 0 && (!best || c.value > best.value)) best = c;
  if (!best || best.value < 0.05) return "No strong risk factor";
  const phrase = NUMERIC_PHRASE[best.feature];
  if (phrase) {
    const dir = (churnModel.coef[best.feature] ?? 0) >= 0 ? phrase.high : phrase.low;
    const value = Number((row as unknown as Record<string, unknown>)[best.feature]);
    return `${dir} (${phrase.fmt(value)})`;
  }
  return featureLabel(best.feature);
}

export const topReason = (row: CustomerRow) => reasonFrom(row, churnContributions(row));

